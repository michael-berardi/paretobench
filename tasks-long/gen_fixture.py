#!/usr/bin/env python3
"""Fixture setup for the long-v1 task set.

usage: python3 gen_fixture.py <dest> [task]
The runner imports this module and calls prepare(dest, task). The repository is generated from a
fixed seed: the static files in fixture/ are copied, the bulk (entity models, handlers, commands,
tests, plugins, parsers, logs and data) is generated by gen_bulk.py, and a per-task setup then plants
what that task needs (a bug, decoys, deprecated calls). Two calls with the same arguments produce
byte-identical trees.
"""
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

import gen_bulk  # noqa: E402  (hashed with the task set: gen_*.py)

SEED = 20261111
TASKS = [f"L{i}" for i in range(1, 12)]


def _copy_static(dest):
    shutil.copytree(os.path.join(HERE, "fixture"), dest, dirs_exist_ok=True,
                    ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))


def read(dest, rel):
    with open(os.path.join(dest, rel), newline="") as f:
        return f.read()


def write(dest, rel, text):
    gen_bulk.w(dest, rel, text)


def replace_once(dest, rel, old, new):
    text = read(dest, rel)
    if text.count(old) != 1:
        raise RuntimeError(f"setup anchor not unique in {rel}: {old!r} x{text.count(old)}")
    write(dest, rel, text.replace(old, new))


def prepare(dest, task=None):
    """Generate the repository in dest and apply the setup for one task (None: the clean base)."""
    if task is not None and task not in TASKS:
        raise ValueError(f"unknown task {task!r}")
    dest = os.path.abspath(dest)
    _copy_static(dest)
    gen_bulk.generate(dest, SEED)
    if task is not None:
        try:
            import gen_setups
        except ImportError:  # pragma: no cover
            return dest
        getattr(gen_setups, "setup_" + task)(dest)
    return dest


if __name__ == "__main__":
    prepare(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else None)
